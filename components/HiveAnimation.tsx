/**
 * HiveAnimation
 * =============
 * A honeycomb lattice with a glowing tangerine signal that draws itself along the
 * grid edges, branches, closes the occasional cell, fades, and loops.
 *
 * How the grid stays seamless
 * ---------------------------
 * The <pattern> tile below draws only the LEFT HALF of each hexagon (three edges).
 * Neighbouring tiles supply the other half, so every edge is drawn exactly once.
 * Drawing whole hexagons would double every shared edge and, at 5% opacity, the
 * doubled lines would render at roughly 10% and the grid would look striped.
 *
 * How the signal follows the grid
 * -------------------------------
 * The path coordinates are not hand-drawn. They were generated by walking the real
 * lattice graph, so every segment lies exactly on a hexagon edge. That is why the
 * glow reads as a signal travelling through the structure rather than a squiggle
 * laid on top of it.
 *
 * The walk is confined to x > 700 in the 1440-wide viewBox, so it occupies the photo
 * half of the hero and leaves the headline column alone. Rotating the whole SVG would
 * have moved it too, but it would also tilt the base grid off-horizontal, which reads
 * as a rendering fault rather than a decision.
 *
 * Framer Motion animates `pathLength`, which under the hood drives strokeDasharray
 * and strokeDashoffset. Opacity is keyframed separately so each path draws in,
 * holds, then dissolves before the loop restarts.
 *
 * Cost and restraint
 * ------------------
 * - `hidden lg:block`: never rendered on phones, where it would cost battery for
 *   decoration nobody asked for.
 * - `useReducedMotion`: visitors who ask for less motion get the static grid only.
 * - `pointer-events-none` and `aria-hidden`: invisible to clicks and screen readers.
 */

