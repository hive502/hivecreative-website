type Props = {
  /** Extra classes for the wrapper, e.g. an opacity override per section. */
  className?: string;
};

export default function HiveAnimation({ className = '' }: Props) {
  const reduceMotion = useReducedMotion();

  return (
    <div
      aria-hidden
      className={`pointer-events-none absolute inset-0 z-0 hidden overflow-hidden lg:block ${className}`}
    >
      <svg
        viewBox="0 0 1440 900"
        preserveAspectRatio="xMidYMid slice"
        className="h-full w-full"
      >
        <defs>
          <pattern
            id="hive-grid"
            width={TILE_W}
            height={TILE_H}
            patternUnits="userSpaceOnUse"
          >
            <path
              d={GRID_D}
              fill="none"
              stroke="#2B3C5A"
              strokeOpacity={0.05}
              strokeWidth={1}
            />
          </pattern>

          {/* Neon bloom: blur the stroke, stack it twice for intensity, then lay
              the crisp stroke back on top so the line core stays sharp. */}
          <filter id="hive-glow" x="-25%" y="-25%" width="150%" height="150%">
            <feGaussianBlur stdDeviation="5" result="blur" />
            <feMerge>
              <feMergeNode in="blur" />
              <feMergeNode in="blur" />
              <feMergeNode in="SourceGraphic" />
            </feMerge>
          </filter>

          {/* Horizontal fade, not radial. The signal is fully masked out across the
              headline column, ramps in over the gutter, and eases off again at the
              far edge so it never terminates in a hard vertical line. Move the 42%
              and 60% stops together to widen or narrow the clear zone. */}
          <linearGradient id="hive-fade" x1="0" y1="0" x2="1" y2="0">
            <stop offset="0%" stopColor="#fff" stopOpacity="0" />
            <stop offset="42%" stopColor="#fff" stopOpacity="0" />
            <stop offset="60%" stopColor="#fff" stopOpacity="0.85" />
            <stop offset="88%" stopColor="#fff" stopOpacity="1" />
            <stop offset="100%" stopColor="#fff" stopOpacity="0.15" />
          </linearGradient>
          <mask id="hive-mask">
            <rect width="1440" height="900" fill="url(#hive-fade)" />
          </mask>
        </defs>

        <rect width="1440" height="900" fill="url(#hive-grid)" />

        {!reduceMotion && (
          <g mask="url(#hive-mask)" filter="url(#hive-glow)">
            {PATHS.map((p) => (
              <motion.path
                key={p.id}
                d={p.d}
                fill="none"
                stroke="#FF8F00"
                strokeWidth={p.width}
                strokeLinecap="round"
                strokeLinejoin="round"
                initial={{ pathLength: 0, opacity: 0 }}
                animate={{ pathLength: [0, 1, 1], opacity: [0, 1, 0] }}
                transition={{
                  // 0 -> 0.62 draws, 0.62 -> 0.82 holds, then it fades out
                  times: [0, 0.62, 1],
                  duration: p.duration,
                  delay: p.delay,
                  ease: 'easeInOut',
                  repeat: Infinity,
                  repeatDelay: 1.4,
                }}
              />
            ))}
          </g>
        )}
      </svg>
    </div>
  );
}
